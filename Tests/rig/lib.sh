# Shared by the local test rig's scripts (up.sh, down.sh, write-config.sh). Source it; do not run it.
# Expects RIG_DIR to be set to this directory.

ROOT="$(cd "$RIG_DIR/../.." && pwd -P)"
CONFIG="$ROOT/configuration/config.ini"
MODE_FILE="$RIG_DIR/.mode"
PID_FILE="$RIG_DIR/.server.pid"

# The first line of every configuration/config.ini the rig writes: the rig may replace (or switch the
# mode of) a file that starts with it, and never touches one that does not.
RIG_MARKER='; idno-test-rig: generated by the local test rig (Tests/rig/); composer test:up may replace this file.'
# The first line the rig wrote before it had a marker; such a file is the rig's too.
RIG_LEGACY_MARKER='; Idno configuration for the local test rig (see Tests/rig/up.sh).'

# Everything the rig keeps outside the repository (the SQLite database, the upload directory) lives
# in one directory under the system temp directory, named after this checkout's real path, so that
# two checkouts (git worktrees) of the repository never share a database or uploads.
STATE_DIR="$(php -r 'echo rtrim(sys_get_temp_dir(), "/"), "/idno-test-rig-", substr(hash("sha256", $argv[1]), 0, 12);' "$ROOT")"

# True when configuration/config.ini was written by the rig: a regular file (never a symlink) whose
# first line is the marker, exactly.
rig_config_is_ours() {
    local first
    [ ! -L "$CONFIG" ] && [ -f "$CONFIG" ] || return 1
    first="$(head -n 1 "$CONFIG")"
    [ "$first" = "$RIG_MARKER" ] || [ "$first" = "$RIG_LEGACY_MARKER" ]
}

# The mode the rig was last started in: sqlite, mysql, or empty when unknown. Read from .mode;
# without it (a rig started before modes existed), from a rig-written configuration/config.ini.
rig_mode() {
    if [ -f "$MODE_FILE" ]; then
        cat "$MODE_FILE"
    elif rig_config_is_ours; then
        if grep -qi "^database = 'sqlite'" "$CONFIG"; then
            echo sqlite
        else
            echo mysql
        fi
    fi
}

# The pid in .server.pid when it is this rig's web server (a live `php ... -S 127.0.0.1:<port>
# ... <this rig's router.php>`); nothing otherwise (no pid file, a dead process, or another program).
rig_server_pid() {
    local pid command
    [ -f "$PID_FILE" ] || return 0
    pid="$(cat "$PID_FILE")"
    case "$pid" in ''|*[!0-9]*) return 0 ;; esac
    command="$(ps -p "$pid" -o command= 2>/dev/null || true)"
    case "$command" in
        *php*" -S 127.0.0.1:"*"$RIG_DIR/router.php"*) echo "$pid" ;;
    esac
}
