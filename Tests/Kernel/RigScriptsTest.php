    {
        $this->runScript('write-config.sh', 'sqlite');
        $settings = parse_ini_string((string) file_get_contents($this->config()));

        $thisCheckout = rtrim(sys_get_temp_dir(), '/') . '/idno-test-rig-' . substr(hash('sha256', (string) realpath(dirname(__DIR__, 2))), 0, 12);
        $this->assertStringStartsNotWith($thisCheckout, $settings['dbname']);
        $this->assertStringStartsWith(rtrim(sys_get_temp_dir(), '/') . '/idno-test-rig-', $settings['dbname']);
    }

    public function testReplacesAConfigTheRigWroteToSwitchModes(): void
    {
        $this->runScript('write-config.sh', 'sqlite');
        [$code, $output] = $this->runScript('write-config.sh', 'mysql');

        $this->assertSame(0, $code, $output);
