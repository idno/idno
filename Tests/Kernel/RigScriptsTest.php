<?php

declare(strict_types=1);

namespace Tests\Kernel;

use PHPUnit\Framework\TestCase;

/**
 * The local test rig's scripts (Tests/rig/up.sh, down.sh, write-config.sh), run against a scratch
 * copy of the project layout in a temporary directory, never against this checkout's
 * configuration/config.ini or its web server: the rig writes a config when there is none, replaces
 * one it wrote (switching modes), and refuses to touch anything else; up.sh switches modes and
 * survives a failed MySQL start; down.sh always cleans up and signals only its own web server. A
 * `docker` shim first on the PATH stands in for Docker; a web server the scripts start listens on a
 * free high port (IDNO_RIG_PORT), never 8089. The two templates differ only in their database settings.
 */
final class RigScriptsTest extends TestCase
{
    private const MARKER = '; idno-test-rig: generated by the local test rig (Tests/rig/); composer test:up may replace this file.';

    private const LEGACY_MARKER = '; Idno configuration for the local test rig (see Tests/rig/up.sh).';

    private string $root = '';

    /** The web server port of this test's scripts (IDNO_RIG_PORT), picked once per test. */
    private int $port = 0;

    /** IDNO_RIG_MYSQL_IMAGE for the scripts this test runs ('' : unset, the default image). */
    private string $mysqlImage = '';

    protected function setUp(): void
    {
        $this->port = self::freePort();
        $this->root = (string) realpath(sys_get_temp_dir()) . '/idno-rig-test-' . bin2hex(random_bytes(6));
        mkdir($this->root . '/Tests/rig', 0777, true);
        mkdir($this->root . '/bin');
        foreach (['lib.sh', 'write-config.sh', 'up.sh', 'down.sh', 'config.ini', 'config.sqlite.ini', 'router.php', 'docker-compose.yml'] as $file) {
            copy(self::rigDir() . '/' . $file, $this->root . '/Tests/rig/' . $file);
            chmod($this->root . '/Tests/rig/' . $file, 0755);
        }
        // up.sh runs `php bin/console idno:upgrade` (from the project root) before it starts the web
        // server: a stand-in that records its arguments, the rig's environment and whether the web
        // server had started, one line per run (and fails, exit 1, when the file console-fails exists).
        $console = <<<'PHP'
            <?php
            $root = dirname(__DIR__);
            file_put_contents($root . '/console.log', implode(' ', array_slice($argv, 1))
                . ' APP_ENV=' . getenv('APP_ENV') . ' APP_DEBUG=' . getenv('APP_DEBUG') . ' error_reporting=' . ini_get('error_reporting')
                . ' server=' . (is_file($root . '/Tests/rig/.server.pid') ? 'yes' : 'no') . "\n", FILE_APPEND);
            if (is_file($root . '/console-fails')) {
                fwrite(STDERR, "the stand-in upgrade failed\n");
                exit(1);
            }

            PHP;
        file_put_contents($this->root . '/bin/console', $console);
    }

    protected function tearDown(): void
    {
        // A web server a test started (listening on a high port in the scratch root): stop it.
        $pidFile = $this->root . '/Tests/rig/.server.pid';
        if (is_file($pidFile)) {
            $pid = (int) file_get_contents($pidFile);
            if ($pid > 0 && str_contains((string) shell_exec('ps -p ' . $pid . ' -o command='), $this->root)) {
                // Its workers (children) outlive it and hold the port.
                exec('pkill -P ' . $pid . ' 2>/dev/null; kill ' . $pid);
            }
        }
        $stateDir = $this->stateDir();
        foreach ([$this->root, $stateDir] as $dir) {
            if (is_dir($dir)) {
                exec('rm -rf ' . escapeshellarg($dir));
            }
        }
    }

    private static function rigDir(): string
    {
        return dirname(__DIR__) . '/rig';
    }

    private function config(): string
    {
        return $this->root . '/configuration/config.ini';
    }

    /**
     * The scratch layout's own directory under the system temp directory (lib.sh's STATE_DIR).
     */
    private function stateDir(): string
    {
        return rtrim(sys_get_temp_dir(), '/') . '/idno-test-rig-' . substr(hash('sha256', $this->root), 0, 12);
    }

    /**
     * @return array{0: int, 1: string} exit code and output (stdout and stderr)
     */
    private function runScript(string $script, string ...$args): array
    {
        $command = 'PATH=' . escapeshellarg($this->root . '/bin:' . (string) getenv('PATH')) . ' '
            . 'IDNO_RIG_PORT=' . $this->port . ' '
            . 'IDNO_RIG_MYSQL_IMAGE=' . escapeshellarg($this->mysqlImage) . ' '
            . escapeshellarg($this->root . '/Tests/rig/' . $script);
        foreach ($args as $arg) {
            $command .= ' ' . escapeshellarg($arg);
        }
        exec($command . ' 2>&1', $output, $code);

        return [$code, implode("\n", $output)];
    }

    /**
     * A TCP port on 127.0.0.1 with nothing listening (never the rig's 8089).
     */
    private static function freePort(): int
    {
        $server = stream_socket_server('tcp://127.0.0.1:0');
        self::assertIsResource($server);
        $name = (string) stream_socket_get_name($server, false);
        fclose($server);
        $port = (int) substr($name, strrpos($name, ':') + 1);
        self::assertNotSame(8089, $port);

        return $port;
    }

    /**
     * A `docker` first on the PATH that logs its arguments, after the image docker compose would
     * interpolate (`[<IDNO_RIG_MYSQL_IMAGE>] `); it fails (exit 1, as with Docker not running) or
     * succeeds.
     */
    private function dockerShim(bool $succeeds): void
    {
        $log = escapeshellarg($this->root . '/docker.log');
        $script = "#!/bin/sh\necho \"[\$IDNO_RIG_MYSQL_IMAGE] \$*\" >> $log\n" . ($succeeds
            ? "exit 0\n"
            : "echo 'Cannot connect to the Docker daemon' >&2\nexit 1\n");
        file_put_contents($this->root . '/bin/docker', $script);
        chmod($this->root . '/bin/docker', 0755);
    }

    /**
     * The runs of the bin/console stand-in, one line each.
     *
     * @return list<string>
     */
    private function consoleRuns(): array
    {
        $file = $this->root . '/console.log';

        return is_file($file) ? array_values(array_filter(explode("\n", (string) file_get_contents($file)))) : [];
    }

    private function dockerLog(): string
    {
        return is_file($this->root . '/docker.log') ? (string) file_get_contents($this->root . '/docker.log') : '';
    }

    private function mode(): ?string
    {
        $file = $this->root . '/Tests/rig/.mode';

        return is_file($file) ? trim((string) file_get_contents($file)) : null;
    }

    private function serverPid(): int
    {
        $file = $this->root . '/Tests/rig/.server.pid';

        return is_file($file) ? (int) file_get_contents($file) : 0;
    }

    private static function isRunning(int $pid): bool
    {
        return $pid > 0 && trim((string) shell_exec('ps -p ' . $pid . ' -o pid=')) !== '';
    }

    public function testWritesTheConfigWhenThereIsNone(): void
    {
        [$code, $output] = $this->runScript('write-config.sh', 'sqlite');

        $this->assertSame(0, $code, $output);
        $config = (string) file_get_contents($this->config());
        $this->assertStringStartsWith(self::MARKER . "\n", $config);
        $settings = parse_ini_string($config);
        $this->assertSame('sqlite', $settings['database']);
        $this->assertSame($this->stateDir() . '/site.sqlite', $settings['dbname']);
        $this->assertSame($this->stateDir() . '/uploads/', $settings['uploadpath']);
    }

