    /**
     * Before the web server starts, in either mode, the rig creates the schema with
     * `bin/console idno:upgrade`, in the rig's environment: APP_ENV=test, APP_DEBUG=1 and
     * deprecations excluded (error_reporting 22527), as `composer console` runs it. It loads no
     * SQL file. Started again, it runs the command again (which does nothing on a database that
     * has the schema) and starts no second server.
     */
    public function testUpCreatesTheSchemaWithTheUpgradeCommandBeforeTheWebServer(): void
    {
        [$code, $output] = $this->runScript('up.sh');
        $this->assertSame(0, $code, $output);
        $this->assertSame(['idno:upgrade APP_ENV=test APP_DEBUG=1 error_reporting=22527 server=no'], $this->consoleRuns());
        $this->assertFileExists($this->stateDir() . '/site.sqlite');
        $this->assertSame(0, filesize($this->stateDir() . '/site.sqlite'), 'the rig makes an empty database file; the command fills it');

        [$code, $output] = $this->runScript('up.sh');
        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('Web server already running', $output);
        $this->assertSame('idno:upgrade APP_ENV=test APP_DEBUG=1 error_reporting=22527 server=yes', $this->consoleRuns()[1]);

        $this->runScript('down.sh');
        $this->dockerShim(true);
        [$code, $output] = $this->runScript('up.sh', 'mysql');
        $this->assertSame(0, $code, $output);
        $this->assertSame('idno:upgrade APP_ENV=test APP_DEBUG=1 error_reporting=22527 server=no', $this->consoleRuns()[2]);
        $this->assertStringNotContainsString('exec', $this->dockerLog(), 'no SQL is loaded into the container');
    }

    /**
     * The rig's web server runs four workers (PHP_CLI_SERVER_WORKERS=4): the site makes requests to
     * itself while it serves another (a webmention to a page of its own, a test route answering an
     * outbound request), which would wait for ever with one worker. Pinned in the script and in the
     * running server, which forks one child per worker.
     */
    public function testTheWebServerRunsFourWorkers(): void
    {
        $this->assertStringContainsString(
            'PHP_CLI_SERVER_WORKERS=4 nohup php',
            (string) file_get_contents(self::rigDir() . '/up.sh'),
            'up.sh starts the web server with four workers'
        );

        [$code, $output] = $this->runScript('up.sh');
        $this->assertSame(0, $code, $output);
        $pid = trim((string) file_get_contents($this->root . '/Tests/rig/.server.pid'));
        $this->assertMatchesRegularExpression('/^\d+$/', $pid);

        $children = [];
        for ($attempt = 0; $attempt < 20; ++$attempt) {
            exec('pgrep -P ' . escapeshellarg($pid) . ' 2>/dev/null', $children);
            if ($children !== []) {
                break;
            }
            usleep(100000);
        }
        $this->assertCount(4, $children, 'the web server forked four workers');

        // down.sh stops the workers too: they outlive their parent and would hold the port.
        [$code, $output] = $this->runScript('down.sh');
        $this->assertSame(0, $code, $output);
        $alive = $children;
        for ($attempt = 0; $attempt < 20 && $alive !== []; ++$attempt) {
            usleep(100000);
            $alive = array_values(array_filter($children, static fn (string $child): bool => posix_kill((int) $child, 0)));
        }
        $this->assertSame([], $alive, 'down.sh stopped the workers');
    }

    /**
     * The rig's web server keeps its sessions in a directory of its own, in the rig's per-checkout temporary directory (the system's
     * shared one holds every test session of every checkout, and PHP's garbage collection of it, run by one request in a thousand, stats
     * every file in it): `session.save_path` is on its command line, the directory is made by up.sh and removed with the rest of the
     * rig's state by down.sh.
     */
    public function testTheWebServerKeepsItsSessionsInADirectoryOfItsOwn(): void
    {
        [$code, $output] = $this->runScript('up.sh');
        $this->assertSame(0, $code, $output);
        $command = (string) shell_exec('ps -p ' . $this->serverPid() . ' -o command=');

        $this->assertStringContainsString(' -d session.save_path=' . $this->stateDir() . '/sessions ', $command);
        $this->assertDirectoryExists($this->stateDir() . '/sessions');

        [$code, $output] = $this->runScript('down.sh');
        $this->assertSame(0, $code, $output);
        $this->assertDirectoryDoesNotExist($this->stateDir() . '/sessions');
    }

    /**
     * down.sh stops every worker of the rig's server, also when the server's own process has died and the workers have been handed to
     * init (a pid it can no longer find them by): up.sh records the workers' pids once the server answers, and down.sh signals those, only
     * while their command line is still this rig's server.
     */
    public function testDownStopsTheWorkersOfAServerWhoseMasterHasDied(): void
    {
        [$code, $output] = $this->runScript('up.sh');
        $this->assertSame(0, $code, $output);
        $master = $this->serverPid();
        $workers = [];
        for ($attempt = 0; $attempt < 20 && count($workers) < 4; ++$attempt) {
            $workers = [];
            exec('pgrep -P ' . $master . ' 2>/dev/null', $workers);
            usleep(100000);
        }
        $this->assertCount(4, $workers);
        exec('kill -KILL ' . $master);
        for ($attempt = 0; $attempt < 50 && self::isRunning($master); ++$attempt) {
            usleep(100000);
        }
        $this->assertFalse(self::isRunning($master), 'the master is dead');
        $this->assertTrue(self::isRunning((int) $workers[0]), 'and its workers are not');

        [$code, $output] = $this->runScript('down.sh');

        $this->assertSame(0, $code, $output);
        for ($attempt = 0; $attempt < 30; ++$attempt) {
            $alive = array_values(array_filter($workers, static fn (string $pid): bool => self::isRunning((int) $pid)));
            if ($alive === []) {
                break;
            }
            usleep(100000);
        }
        $this->assertSame([], $alive, 'down.sh stopped the workers');
    }

    /**
     * What down.sh signals is what up.sh recorded and only while the process is still the rig's server: a recorded pid that another
     * program has since been given is left alone.
     */
    public function testDownDoesNotSignalARecordedWorkerThatIsAnotherProgramNow(): void
    {
        $sleep = proc_open(['sleep', '30'], [], $pipes);
        $this->assertIsResource($sleep);
        try {
            $pid = proc_get_status($sleep)['pid'];
            mkdir($this->stateDir(), 0777, true);
            file_put_contents($this->stateDir() . '/server.workers', $pid . "\n");
            file_put_contents($this->root . '/Tests/rig/.mode', "sqlite\n");

            [$code, $output] = $this->runScript('down.sh');

            $this->assertSame(0, $code, $output);
            usleep(200000);
            $this->assertTrue(proc_get_status($sleep)['running'], 'the unrelated process survived');
        } finally {
            proc_terminate($sleep);
            proc_close($sleep);
        }
    }

    /**
     * When the upgrade command fails, up.sh says which step failed on stderr, exits non-zero and
     * starts no web server; the mode stays recorded, so down.sh cleans up.
     */
    public function testAFailedUpgradeStopsTheStartWithAMessage(): void
    {
        touch($this->root . '/console-fails');

        [$code, $output] = $this->runScript('up.sh');

        $this->assertNotSame(0, $code, $output);
        $this->assertStringContainsString('the stand-in upgrade failed', $output);
        $this->assertStringContainsString('The test rig could not create the schema: bin/console idno:upgrade failed', $output);
        $this->assertSame(0, $this->serverPid(), 'no web server was started');
        $this->assertSame('sqlite', $this->mode());

        [$code, $output] = $this->runScript('down.sh');
        $this->assertSame(0, $code, $output);
        $this->assertDirectoryDoesNotExist($this->stateDir());
    }

