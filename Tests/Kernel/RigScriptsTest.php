    public function testDownWithAFailingDockerStillCleansUp(): void
    {
        $this->dockerShim(false);
        $this->runScript('write-config.sh', 'mysql');
        file_put_contents($this->root . '/Tests/rig/.mode', "mysql\n");
        mkdir($this->stateDir() . '/uploads', 0777, true);

        [$code, $output] = $this->runScript('down.sh');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('warning: could not stop the test rig\'s MySQL container', $output);
        $this->assertStringContainsString('compose -f ' . $this->root . '/Tests/rig/docker-compose.yml down -v', $this->dockerLog());
        $this->assertDirectoryDoesNotExist($this->stateDir());
        $this->assertNull($this->mode());
    }

    public function testAFailedMysqlStartLeavesTheDefaultStartWorking(): void
    {
        $this->dockerShim(false);

        [$code, $output] = $this->runScript('up.sh', 'mysql');
        $this->assertNotSame(0, $code, $output);
        $this->assertNull($this->mode(), 'no mode is recorded for a database that never came up');
        $this->assertSame(0, $this->serverPid(), 'no web server was started');

        [$code, $output] = $this->runScript('up.sh');
        $this->assertSame(0, $code, $output);
        $this->assertSame('sqlite', $this->mode());
        $this->assertFileExists($this->stateDir() . '/site.sqlite');
        $this->assertSame('sqlite', parse_ini_file($this->config())['database']);
        $pid = $this->serverPid();
        $this->assertTrue(self::isRunning($pid));
        $this->assertStringNotContainsString('down', $this->dockerLog(), 'nothing had to be stopped');

        [$code, $output] = $this->runScript('down.sh');
        $this->assertSame(0, $code, $output);
        usleep(200_000);
        $this->assertFalse(self::isRunning($pid));
    }

    public function testAStaleMysqlModeFileWithNothingRunningDoesNotBlockSqlite(): void
