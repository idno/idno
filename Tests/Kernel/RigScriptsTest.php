<?php

declare(strict_types=1);

namespace Tests\Kernel;

use PHPUnit\Framework\TestCase;

/**
 * The local test rig's scripts (Tests/rig/up.sh, down.sh, write-config.sh), run against a scratch
 * copy of the project layout in a temporary directory, never against this checkout's
 * configuration/config.ini or its web server: the rig writes a config when there is none, replaces
 * one it wrote (switching modes), and refuses to touch anything else; up.sh switches modes and
 * survives a failed MySQL start; down.sh always cleans up and signals only its own web server. A
 * `docker` shim first on the PATH stands in for Docker; a web server the scripts start listens on a
 * free high port (IDNO_RIG_PORT), never 8089. The two templates differ only in their database settings.
 */
final class RigScriptsTest extends TestCase
{
    private const MARKER = '; idno-test-rig: generated by the local test rig (Tests/rig/); composer test:up may replace this file.';

    private const LEGACY_MARKER = '; Idno configuration for the local test rig (see Tests/rig/up.sh).';

    private string $root = '';

    /** The web server port of this test's scripts (IDNO_RIG_PORT), picked once per test. */
    private int $port = 0;

    /** IDNO_RIG_MYSQL_IMAGE for the scripts this test runs ('' : unset, the default image). */
    private string $mysqlImage = '';

    protected function setUp(): void
    {
        $this->port = self::freePort();
        $this->root = (string) realpath(sys_get_temp_dir()) . '/idno-rig-test-' . bin2hex(random_bytes(6));
        mkdir($this->root . '/Tests/rig', 0777, true);
        mkdir($this->root . '/bin');
        foreach (['lib.sh', 'write-config.sh', 'up.sh', 'down.sh', 'config.ini', 'config.sqlite.ini', 'router.php', 'sqlite_schema.php', 'docker-compose.yml'] as $file) {
            copy(self::rigDir() . '/' . $file, $this->root . '/Tests/rig/' . $file);
            chmod($this->root . '/Tests/rig/' . $file, 0755);
        }
        // sqlite_schema.php loads the autoloader from the project root.
        symlink(dirname(__DIR__, 2) . '/vendor', $this->root . '/vendor');
    }

    protected function tearDown(): void
    {
        // A web server a test started (listening on a high port in the scratch root): stop it.
        $pidFile = $this->root . '/Tests/rig/.server.pid';
        if (is_file($pidFile)) {
            $pid = (int) file_get_contents($pidFile);
            if ($pid > 0 && str_contains((string) shell_exec('ps -p ' . $pid . ' -o command='), $this->root)) {
                exec('kill ' . $pid);
            }
        }
        $stateDir = $this->stateDir();
        foreach ([$this->root, $stateDir] as $dir) {
            if (is_dir($dir)) {
                exec('rm -rf ' . escapeshellarg($dir));
            }
        }
    }

    private static function rigDir(): string
    {
        return dirname(__DIR__) . '/rig';
    }

    private function config(): string
    {
        return $this->root . '/configuration/config.ini';
    }

    /**
     * The scratch layout's own directory under the system temp directory (lib.sh's STATE_DIR).
     */
    private function stateDir(): string
    {
        return rtrim(sys_get_temp_dir(), '/') . '/idno-test-rig-' . substr(hash('sha256', $this->root), 0, 12);
    }

    /**
     * @return array{0: int, 1: string} exit code and output (stdout and stderr)
     */
    private function runScript(string $script, string ...$args): array
    {
        $command = 'PATH=' . escapeshellarg($this->root . '/bin:' . (string) getenv('PATH')) . ' '
            . 'IDNO_RIG_PORT=' . $this->port . ' '
            . 'IDNO_RIG_MYSQL_IMAGE=' . escapeshellarg($this->mysqlImage) . ' '
            . escapeshellarg($this->root . '/Tests/rig/' . $script);
        foreach ($args as $arg) {
            $command .= ' ' . escapeshellarg($arg);
        }
        exec($command . ' 2>&1', $output, $code);

        return [$code, implode("\n", $output)];
    }

    /**
     * A TCP port on 127.0.0.1 with nothing listening (never the rig's 8089).
     */
    private static function freePort(): int
    {
        $server = stream_socket_server('tcp://127.0.0.1:0');
        self::assertIsResource($server);
        $name = (string) stream_socket_get_name($server, false);
        fclose($server);
        $port = (int) substr($name, strrpos($name, ':') + 1);
        self::assertNotSame(8089, $port);

        return $port;
    }

    /**
     * A `docker` first on the PATH that logs its arguments, after the image docker compose would
     * interpolate (`[<IDNO_RIG_MYSQL_IMAGE>] `); it fails (exit 1, as with Docker not running) or
     * succeeds (and then answers the schema check as if the database had tables).
     */
    private function dockerShim(bool $succeeds): void
    {
        $log = escapeshellarg($this->root . '/docker.log');
        $script = "#!/bin/sh\necho \"[\$IDNO_RIG_MYSQL_IMAGE] \$*\" >> $log\n" . ($succeeds
            ? "case \"\$*\" in *'SHOW TABLES'*) echo versions ;; esac\nexit 0\n"
            : "echo 'Cannot connect to the Docker daemon' >&2\nexit 1\n");
        file_put_contents($this->root . '/bin/docker', $script);
        chmod($this->root . '/bin/docker', 0755);
    }

    private function dockerLog(): string
    {
        return is_file($this->root . '/docker.log') ? (string) file_get_contents($this->root . '/docker.log') : '';
    }

    private function mode(): ?string
    {
        $file = $this->root . '/Tests/rig/.mode';

        return is_file($file) ? trim((string) file_get_contents($file)) : null;
    }

    private function serverPid(): int
    {
        $file = $this->root . '/Tests/rig/.server.pid';

        return is_file($file) ? (int) file_get_contents($file) : 0;
    }

    private static function isRunning(int $pid): bool
    {
        return $pid > 0 && trim((string) shell_exec('ps -p ' . $pid . ' -o pid=')) !== '';
    }

    public function testWritesTheConfigWhenThereIsNone(): void
    {
        [$code, $output] = $this->runScript('write-config.sh', 'sqlite');

        $this->assertSame(0, $code, $output);
        $config = (string) file_get_contents($this->config());
        $this->assertStringStartsWith(self::MARKER . "\n", $config);
        $settings = parse_ini_string($config);
        $this->assertSame('sqlite', $settings['database']);
        $this->assertSame($this->stateDir() . '/site.sqlite', $settings['dbname']);
        $this->assertSame($this->stateDir() . '/uploads/', $settings['uploadpath']);
    }

    public function testEachCheckoutHasItsOwnTemporaryDirectory(): void
    {
        $this->runScript('write-config.sh', 'sqlite');
        $settings = parse_ini_string((string) file_get_contents($this->config()));

        $thisCheckout = rtrim(sys_get_temp_dir(), '/') . '/idno-test-rig-' . substr(hash('sha256', (string) realpath(dirname(__DIR__, 2))), 0, 12);
        $this->assertStringStartsNotWith($thisCheckout, $settings['dbname']);
        $this->assertStringStartsWith(rtrim(sys_get_temp_dir(), '/') . '/idno-test-rig-', $settings['dbname']);
    }

    public function testReplacesAConfigTheRigWroteToSwitchModes(): void
    {
        $this->runScript('write-config.sh', 'sqlite');
        [$code, $output] = $this->runScript('write-config.sh', 'mysql');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('Replaced', $output);
        $settings = parse_ini_string((string) file_get_contents($this->config()));
        $this->assertSame('MySQL', $settings['database']);
        $this->assertSame('known_unittest', $settings['dbname']);

        [$code, $output] = $this->runScript('write-config.sh', 'mysql');
        $this->assertSame(0, $code, $output);
        $this->assertSame('', $output, 'an unchanged config is left alone');
    }

    public function testReplacesAConfigTheRigWroteBeforeItHadAMarker(): void
    {
        mkdir($this->root . '/configuration');
        file_put_contents($this->config(), self::LEGACY_MARKER . "\ndatabase = 'MySQL'\ndbname = 'known_unittest'\n");

        [$code, $output] = $this->runScript('write-config.sh', 'sqlite');

        $this->assertSame(0, $code, $output);
        $this->assertSame('sqlite', parse_ini_string((string) file_get_contents($this->config()))['database']);
    }

    public function testNeverTouchesADevelopersOwnConfig(): void
    {
        mkdir($this->root . '/configuration');
        $own = "; my site\ndatabase = 'MySQL'\ndbname = 'mine'\n";
        file_put_contents($this->config(), $own);

        foreach ([['sqlite'], ['mysql'], ['sqlite', '--check']] as $args) {
            [$code, $output] = $this->runScript('write-config.sh', ...$args);
            $this->assertSame(1, $code, $output);
            $this->assertStringContainsString('was not written by the test rig', $output);
            $this->assertSame($own, file_get_contents($this->config()));
        }
    }

    /**
     * @return array<string, array{0: string}>
     */
    public static function filesThatAreNotTheRigs(): array
    {
        return [
            'an empty file' => [''],
            'CRLF line endings' => [self::MARKER . "\r\ndatabase = 'MySQL'\r\n"],
            'the marker on the second line' => ["; mine\n" . self::MARKER . "\ndatabase = 'MySQL'\n"],
        ];
    }

    /**
     * @dataProvider filesThatAreNotTheRigs
     */
    public function testRefusesAFileThatDoesNotStartWithTheMarker(string $contents): void
    {
        mkdir($this->root . '/configuration');
        file_put_contents($this->config(), $contents);

        foreach ([['sqlite'], ['mysql'], ['sqlite', '--check']] as $args) {
            [$code, $output] = $this->runScript('write-config.sh', ...$args);
            $this->assertSame(1, $code, $output);
            $this->assertStringContainsString('was not written by the test rig', $output);
            $this->assertSame($contents, file_get_contents($this->config()));
        }
    }

    public function testRefusesASymlinkEvenToARigConfig(): void
    {
        mkdir($this->root . '/configuration');
        $target = $this->root . '/elsewhere.ini';
        $contents = self::MARKER . "\ndatabase = 'MySQL'\n";
        file_put_contents($target, $contents);
        symlink($target, $this->config());

        [$code, $output] = $this->runScript('write-config.sh', 'sqlite');

        $this->assertSame(1, $code, $output);
        $this->assertTrue(is_link($this->config()));
        $this->assertSame($contents, file_get_contents($target), 'the target is untouched');
    }

    public function testRefusesADanglingSymlink(): void
    {
        mkdir($this->root . '/configuration');
        $target = $this->root . '/missing/config.ini';
        symlink($target, $this->config());

        foreach ([['sqlite'], ['mysql', '--check']] as $args) {
            [$code, $output] = $this->runScript('write-config.sh', ...$args);
            $this->assertSame(1, $code, $output);
            $this->assertTrue(is_link($this->config()));
            $this->assertFileDoesNotExist($target, 'nothing is written through the link');
        }
    }

    public function testDownWithAFailingDockerStillCleansUp(): void
    {
        $this->dockerShim(false);
        $this->runScript('write-config.sh', 'mysql');
        file_put_contents($this->root . '/Tests/rig/.mode', "mysql\n");
        mkdir($this->stateDir() . '/uploads', 0777, true);

        [$code, $output] = $this->runScript('down.sh');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('warning: could not stop the test rig\'s MySQL container', $output);
        $this->assertStringContainsString('compose -f ' . $this->root . '/Tests/rig/docker-compose.yml down -v', $this->dockerLog());
        $this->assertDirectoryDoesNotExist($this->stateDir());
        $this->assertNull($this->mode());
    }

    public function testAFailedMysqlStartLeavesTheDefaultStartWorking(): void
    {
        $this->dockerShim(false);

        [$code, $output] = $this->runScript('up.sh', 'mysql');
        $this->assertNotSame(0, $code, $output);
        $this->assertNull($this->mode(), 'no mode is recorded for a database that never came up');
        $this->assertSame(0, $this->serverPid(), 'no web server was started');

        [$code, $output] = $this->runScript('up.sh');
        $this->assertSame(0, $code, $output);
        $this->assertSame('sqlite', $this->mode());
        $this->assertFileExists($this->stateDir() . '/site.sqlite');
        $this->assertSame('sqlite', parse_ini_file($this->config())['database']);
        $pid = $this->serverPid();
        $this->assertTrue(self::isRunning($pid));
        $this->assertStringNotContainsString('down', $this->dockerLog(), 'nothing had to be stopped');

        [$code, $output] = $this->runScript('down.sh');
        $this->assertSame(0, $code, $output);
        usleep(200_000);
        $this->assertFalse(self::isRunning($pid));
    }

    public function testAStaleMysqlModeFileWithNothingRunningDoesNotBlockSqlite(): void
    {
        $this->dockerShim(false);
        $this->runScript('write-config.sh', 'mysql');
        file_put_contents($this->root . '/Tests/rig/.mode', "mysql\n");

        [$code, $output] = $this->runScript('up.sh', 'sqlite');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('last started in mysql mode: stopping it first', $output);
        $this->assertStringContainsString('warning: could not stop the test rig\'s MySQL container', $output);
        $this->assertSame('sqlite', $this->mode());
        $this->assertTrue(self::isRunning($this->serverPid()));
    }

    public function testStartingMysqlWhileSqliteRunsStopsSqliteFirst(): void
    {
        [$code, $output] = $this->runScript('up.sh', 'sqlite');
        $this->assertSame(0, $code, $output);
        $sqlitePid = $this->serverPid();
        $this->assertTrue(self::isRunning($sqlitePid));

        $this->dockerShim(true);
        [$code, $output] = $this->runScript('up.sh', 'mysql');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('last started in sqlite mode: stopping it first', $output);
        usleep(200_000);
        $this->assertFalse(self::isRunning($sqlitePid), 'the SQLite rig\'s server was stopped');
        $this->assertFileDoesNotExist($this->stateDir() . '/site.sqlite', 'and its database deleted');
        $this->assertStringContainsString('up -d --wait', $this->dockerLog());
        $this->assertSame('mysql', $this->mode());
        $this->assertSame('MySQL', parse_ini_file($this->config())['database']);
        $this->assertTrue(self::isRunning($this->serverPid()));
    }

    public function testDownDoesNotSignalAProcessThatIsNotTheRigsServer(): void
    {
        $sleep = proc_open(['sleep', '30'], [], $pipes);
        $this->assertIsResource($sleep);
        try {
            $pid = proc_get_status($sleep)['pid'];
            file_put_contents($this->root . '/Tests/rig/.server.pid', $pid . "\n");
            file_put_contents($this->root . '/Tests/rig/.mode', "sqlite\n");

            [$code, $output] = $this->runScript('down.sh');

            $this->assertSame(0, $code, $output);
            $this->assertStringContainsString('does not name this rig\'s web server', $output);
            usleep(200_000);
            $this->assertTrue(proc_get_status($sleep)['running'], 'the unrelated process survived');
            $this->assertFileDoesNotExist($this->root . '/Tests/rig/.server.pid');
        } finally {
            proc_terminate($sleep);
            proc_close($sleep);
        }
    }

    public function testDownInSqliteModeRemovesTheTemporaryDirectoryWithoutRunningDocker(): void
    {
        // A docker that records being run, first on the PATH.
        file_put_contents($this->root . '/bin/docker', "#!/bin/sh\ntouch " . escapeshellarg($this->root . '/docker-was-run') . "\n");
        chmod($this->root . '/bin/docker', 0755);
        $this->runScript('write-config.sh', 'sqlite');
        file_put_contents($this->root . '/Tests/rig/.mode', "sqlite\n");
        mkdir($this->stateDir() . '/uploads', 0777, true);
        touch($this->stateDir() . '/site.sqlite');

        [$code, $output] = $this->runScript('down.sh');

        $this->assertSame(0, $code, $output);
        $this->assertDirectoryDoesNotExist($this->stateDir());
        $this->assertFileDoesNotExist($this->root . '/Tests/rig/.mode');
        $this->assertFileExists($this->config(), 'down leaves the config as it is');

        [$code, $output] = $this->runScript('down.sh');
        $this->assertSame(0, $code, 'down is safe when nothing is running: ' . $output);
        $this->assertFileDoesNotExist($this->root . '/docker-was-run', 'neither down ran docker');
    }

    public function testDownInMysqlModeStopsTheContainer(): void
    {
        file_put_contents($this->root . '/bin/docker', "#!/bin/sh\necho \"\$@\" > " . escapeshellarg($this->root . '/docker-was-run') . "\n");
        chmod($this->root . '/bin/docker', 0755);
        $this->runScript('write-config.sh', 'mysql');

        [$code, $output] = $this->runScript('down.sh');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('compose -f ' . $this->root . '/Tests/rig/docker-compose.yml down -v', (string) file_get_contents($this->root . '/docker-was-run'), 'the data volume goes too');
    }

    public function testTheMysqlModeRunsMysql8UnlessAnImageIsChosen(): void
    {
        $compose = (string) file_get_contents(self::rigDir() . '/docker-compose.yml');
        $this->assertStringContainsString('image: ${IDNO_RIG_MYSQL_IMAGE:-mysql:8.0}', $compose);

        $this->dockerShim(true);
        [$code, $output] = $this->runScript('up.sh', 'mysql');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('[mysql:8.0] compose -f ' . $this->root . '/Tests/rig/docker-compose.yml up -d --wait --renew-anon-volumes', $this->dockerLog());
        $this->assertStringContainsString('mysql:8.0 on 127.0.0.1:33306', $output);
    }

    public function testStartingAnotherImageStopsTheRunningDatabaseFirst(): void
    {
        $this->dockerShim(true);
        [$code, $output] = $this->runScript('up.sh', 'mysql');
        $this->assertSame(0, $code, $output);

        $this->mysqlImage = 'mariadb:10.6';
        [$code, $output] = $this->runScript('up.sh', 'mysql');

        $this->assertSame(0, $code, $output);
        $this->assertStringContainsString('The test rig\'s database runs mysql:8.0, not mariadb:10.6: stopping it first.', $output);
        $log = $this->dockerLog();
        $down = strpos($log, 'docker-compose.yml down -v');
        $this->assertNotFalse($down, $log);
        $this->assertGreaterThan($down, strpos($log, '[mariadb:10.6] compose -f ' . $this->root . '/Tests/rig/docker-compose.yml up -d --wait'), 'MariaDB starts after MySQL and its data are gone');
        $this->assertStringContainsString('[mariadb:10.6] compose -f ' . $this->root . '/Tests/rig/docker-compose.yml exec -T db', $log, 'the schema check runs on the new image');
        $this->assertSame('mysql', $this->mode());

        // The same image again: nothing is stopped.
        file_put_contents($this->root . '/docker.log', '');
        [$code, $output] = $this->runScript('up.sh', 'mysql');
        $this->assertSame(0, $code, $output);
        $this->assertStringNotContainsString('stopping it first', $output);
        $this->assertStringNotContainsString('docker-compose.yml down', $this->dockerLog());
    }

    public function testTheTwoTemplatesDifferOnlyInTheirDatabaseSettings(): void
    {
        $mysql = (string) file_get_contents(self::rigDir() . '/config.ini');
        $sqlite = (string) file_get_contents(self::rigDir() . '/config.sqlite.ini');
        $this->assertStringStartsWith(self::MARKER . "\n", $mysql);
        $this->assertStringStartsWith(self::MARKER . "\n", $sqlite);

        $withoutDatabase = static fn (string $ini): array => array_values(array_filter(
            explode("\n", $ini),
            static fn (string $line): bool => preg_match('/^(database|db[a-z]+) =|^; (MySQL|SQLite) mode/', $line) !== 1,
        ));
        $this->assertSame($withoutDatabase($mysql), $withoutDatabase($sqlite));
    }

    public function testTheRigLoadsTheSamePluginsAsCi(): void
    {
        $rig = parse_ini_file(self::rigDir() . '/config.sqlite.ini')['alwaysplugins'] ?? null;
        $this->assertNotEmpty($rig);
        $this->assertSame($rig, parse_ini_file(self::rigDir() . '/config.ini')['alwaysplugins'] ?? null);
        // The configurations CI copies to configuration/config.ini (.github/workflows/tests.yml).
        foreach (['config_mysql.ini', 'config_default.ini'] as $ci) {
            $this->assertSame($rig, parse_ini_file(dirname(__DIR__) . '/build/' . $ci)['alwaysplugins'] ?? null, $ci);
        }
    }
