<?php

namespace IdnoPlugins\ActivityPub\Pages;

use IdnoPlugins\ActivityPub\ActivityBuilder;

/**
 * Serves QuoteAuthorization stamps for quote post verification (FEP-044f).
 *
 * Remote servers fetch a stamp to verify that a quote was authorized by the quoted post's
 * author. The stamp's address holds the quoted post, the quoting post and an HMAC of both,
 * so that only this site can have made it; nothing is stored.
 *
 * Route: /activitypub/quote-stamp/<quoted post>/<quoting post>/<hmac>, the two posts' URIs
 * as unpadded base64url (see ActivityBuilder::buildQuoteStampUrl() for why).
 *
 * Stamps given out earlier have the address /activitypub/quote-stamp?target=...&object=...&sig=...
 * and are still served, with that address as their id.
 *
 * A stamp is served only while the quoted post is one that other servers may have: when the
 * post is deleted, unpublished or made private, its stamps are gone (404).
 */
class QuoteStamp extends \Idno\Common\Page
{

    function getContent()
    {
        if (count($this->arguments) >= 3) {
            $target = ActivityBuilder::base64UrlDecode((string) $this->arguments[0]);
            $object = ActivityBuilder::base64UrlDecode((string) $this->arguments[1]);
            $sig = (string) $this->arguments[2];
            $legacy = false;
        } else {
            $target = $this->getInput('target', '');
            $object = $this->getInput('object', '');
            $sig = $this->getInput('sig', '');
            $legacy = true;
        }

        if (!is_string($target) || !is_string($object) || !is_string($sig) || $target === '' || $object === '' || $sig === '') {
            $this->answer($legacy ? 400 : 404, ['error' => $legacy ? 'Missing parameters' : 'Not found']);
        }

        // Verify the HMAC to ensure this stamp URL was generated by us
        if (!hash_equals(ActivityBuilder::quoteStampSignature($target, $object), $sig)) {
            $this->answer(404, ['error' => 'Not found']);
        }

        // The quoted post must still be one that other servers may have
        $entity = \Idno\Common\Entity::getByUUID($target);
        if (!ActivityBuilder::isFederated($entity) || $entity->getUUID() !== $target) {
            $this->answer(404, ['error' => 'Not found']);
        }

        $id = $legacy
            ? ActivityBuilder::buildLegacyQuoteStampUrl($target, $object)
            : ActivityBuilder::buildQuoteStampUrl($target, $object);

        header('Access-Control-Allow-Origin: *');
        header('Cache-Control: max-age=3600, public');
        $this->answer(200, ActivityBuilder::buildQuoteAuthorization($entity, $object, $id), 'application/activity+json');
    }

    function postContent()
    {
        header('Allow: GET');
        $this->answer(405, ['error' => 'Method not allowed']);
    }

    private function answer(int $status, array $document, string $type = 'application/json')
    {
        $this->setResponse($status);
        http_response_code($status);
        header('Content-Type: ' . $type);
        echo json_encode($document, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);
        exit;
    }
}
